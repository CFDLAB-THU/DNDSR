#!/usr/bin/env python3
"""Generate the bounded C/M/D CUDA RHS catalog using only Python's stdlib.

The manifest is the single shape registry. Each generated CUDA translation unit
launches one logical specialization of the shared private implementation; block
size and all optional input roles remain runtime controls. Generated files belong
in a build directory. Existing files are replaced only when their content changes.
"""

import argparse
import json
import os
from pathlib import Path
import sys
import tempfile


def read_shapes(manifest):
    """Validate the human-maintained catalog and return deterministic tuples."""
    data = json.loads(manifest.read_text(encoding="utf-8"))
    expected_keys = {"schema_version", "component_counts", "modes_by_dimension"}
    if not isinstance(data, dict) or set(data) != expected_keys:
        raise ValueError("manifest must contain schema_version, component_counts and modes_by_dimension")
    if data["schema_version"] != 1:
        raise ValueError("unsupported manifest schema_version")
    component_counts = data["component_counts"]
    if not isinstance(component_counts, list) or not component_counts:
        raise ValueError("component_counts must be a nonempty list")
    if any(type(value) is not int or value <= 0 for value in component_counts):
        raise ValueError("component_counts must contain positive integers")
    if len(set(component_counts)) != len(component_counts):
        raise ValueError("component_counts contains a duplicate")
    modes_by_dimension = data["modes_by_dimension"]
    if not isinstance(modes_by_dimension, dict) or set(modes_by_dimension) != {"2", "3"}:
        raise ValueError("modes_by_dimension must define dimensions 2 and 3")
    for dimension, modes in modes_by_dimension.items():
        if not isinstance(modes, list) or not modes:
            raise ValueError("dimension {} must have a nonempty mode list".format(dimension))
        if any(type(value) is not int or value < 0 for value in modes):
            raise ValueError("mode counts must be nonnegative integers")
        if len(set(modes)) != len(modes) or 0 not in modes:
            raise ValueError("each dimension must have unique modes including non-VR mode 0")
    return [
        (components, modes, dimension)
        for components in sorted(component_counts)
        for dimension in sorted(int(value) for value in modes_by_dimension)
        for modes in sorted(modes_by_dimension[str(dimension)])
    ]


def write_if_changed(path, content):
    """Publish a complete UTF-8 file atomically without changing equal files."""
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=path.parent, prefix=path.name + ".", delete=False) as stream:
            temporary_path = Path(stream.name)
            stream.write(content)
        os.replace(temporary_path, path)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()


def launch_name(components, modes, dimension):
    return "LaunchRHS_C{}_M{}_D{}".format(components, modes, dimension)


def source_name(components, modes, dimension):
    return "FiniteVolumeRHSKernels_C{}_M{}_D{}.cu".format(components, modes, dimension)


def cuda_source(shape):
    components, modes, dimension = shape
    return """// Generated by scripts/generate_cauchy_rhs.py; do not edit.
#include "Cauchy/Discretization/CUDA/FiniteVolumeRHSKernels_Polynomial_Impl.cu.inc"

namespace DNDS::Cauchy::CUDA::Detail
{{
    void {name}(const RHSFaceLaunch &a)
    {{
        LaunchRHSShape<{components}, {modes}, {dimension}>(a);
    }}
}}
""".format(name=launch_name(*shape), components=components, modes=modes, dimension=dimension)


def declarations(shapes):
    lines = [
        "// Generated by scripts/generate_cauchy_rhs.py; do not edit.",
        "#pragma once", "", "namespace DNDS::Cauchy::CUDA::Detail", "{",
        "    struct RHSFaceLaunch;", "",
        "    /// Dispatch only the manifest's valid C/M/D polynomial RHS shapes.",
        "    void LaunchFP64RHS(const RHSFaceLaunch &a);", "",
    ]
    lines.extend("    void {}(const RHSFaceLaunch &a);".format(launch_name(*shape)) for shape in shapes)
    lines.extend(["}", ""])
    return "\n".join(lines)


def dispatcher(shapes):
    lines = [
        "// Generated by scripts/generate_cauchy_rhs.py; do not edit.",
        '#include "Cauchy/Discretization/CUDA/FiniteVolumeRHSKernels_Shapes.hpp"',
        '#include "FiniteVolumeRHSKernels_Instantiations.hpp"', "",
        "namespace DNDS::Cauchy::CUDA::Detail", "{",
        "    void LaunchFP64RHS(const RHSFaceLaunch &a)", "    {",
        "        const bool nonVR = a.controls.direct || a.controls.firstOrder;",
        "        const int modes = nonVR ? 0 : a.controls.modes;",
        "        DNDS_check_throw_info(nonVR || modes != 0,",
        '                              "CUDA polynomial RHS requires a nonzero VR modal count");',
        "        switch (a.controls.components)", "        {",
    ]
    for components in sorted({shape[0] for shape in shapes}):
        lines.extend(["        case {}:".format(components),
                      "            switch (a.controls.dimension)", "            {"])
        for dimension in sorted({shape[2] for shape in shapes if shape[0] == components}):
            lines.extend(["            case {}:".format(dimension),
                          "                switch (modes)", "                {"])
            for shape in shapes:
                if shape[0] == components and shape[2] == dimension:
                    lines.extend(["                case {}:".format(shape[1]),
                                  "                    return {}(a);".format(launch_name(*shape))])
            lines.extend(["                }", "                break;"])
        lines.extend(["            }", "            break;"])
    lines.extend([
        "        }", "        DNDS_check_throw_info(false,",
        '                              "CUDA polynomial RHS: unsupported component/dimension/modal shape");',
        "    }", "}", "",
    ])
    return "\n".join(lines)


def cmake_path(path):
    """Use bracket arguments so absolute paths are not interpreted by CMake."""
    value = path.as_posix()
    if "]==]" in value or ";" in value or "\n" in value or "\r" in value:
        raise ValueError("generated output path contains an unsupported CMake list character")
    return "[==[{}]==]".format(value)


def cmake_index(output_directory, sources, outputs, declarations_path):
    lines = ["# Generated by scripts/generate_cauchy_rhs.py; do not edit."]
    for variable, values in [
        ("DNDS_CAUCHY_RHS_GENERATED_SOURCES", sources),
        ("DNDS_CAUCHY_RHS_GENERATED_OUTPUTS", outputs),
    ]:
        lines.append("set({}".format(variable))
        lines.extend("    {}".format(cmake_path(path)) for path in values)
        lines.append(")")
    lines.append("set(DNDS_CAUCHY_RHS_GENERATED_INCLUDE_DIR {})".format(cmake_path(output_directory)))
    lines.append("set(DNDS_CAUCHY_RHS_GENERATED_DECLARATIONS {})".format(cmake_path(declarations_path)))
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    try:
        shapes = read_shapes(args.manifest)
        output_directory = args.output_dir.resolve()
        output_directory.mkdir(parents=True, exist_ok=True)
        header = output_directory / "FiniteVolumeRHSKernels_Instantiations.hpp"
        dispatch = output_directory / "FiniteVolumeRHSKernels_Instantiations.cpp"
        index = output_directory / "FiniteVolumeRHSKernels_Sources.cmake"
        cuda_sources = [output_directory / source_name(*shape) for shape in shapes]
        sources = [dispatch] + cuda_sources
        outputs = sources + [header, index]
        # Render everything before publishing any output. The index is published
        # last so configuration cannot accept an incomplete generated source list.
        contents = [(path, cuda_source(shape)) for path, shape in zip(cuda_sources, shapes)]
        contents.extend([(header, declarations(shapes)), (dispatch, dispatcher(shapes))])
        contents.append((index, cmake_index(output_directory, sources, outputs, header)))
        for path, content in contents:
            write_if_changed(path, content)
    except (OSError, ValueError, TypeError) as error:
        print("generate_cauchy_rhs: {}".format(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

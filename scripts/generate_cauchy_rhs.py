#!/usr/bin/env python3
"""Generate the bounded C/M/D CUDA RHS catalog using only Python's stdlib.

The manifest is the single shape registry. Each generated CUDA translation unit
launches one logical specialization of the shared private implementation; block
size and all optional input roles remain runtime controls. Generated files belong
in a build directory. Existing files are replaced only when their content changes.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile

ACM_MAPPINGS = ("Thread", "CTASegments")


def read_shapes(manifest, mechanical=False):
    """Validate the human-maintained catalog and return deterministic tuples."""
    data = json.loads(manifest.read_text(encoding="utf-8"))
    expected_keys = {"schema_version", "component_counts", "modes_by_dimension"}
    if not isinstance(data, dict) or set(data) != expected_keys | {"acm_component_counts"}:
        raise ValueError("manifest must contain both equation families and modes by dimension")
    if data["schema_version"] != 1:
        raise ValueError("unsupported manifest schema_version")
    component_counts = data["acm_component_counts" if mechanical else "component_counts"]
    if not isinstance(component_counts, list) or not component_counts:
        raise ValueError("component_counts must be a nonempty list")
    if any(type(value) is not int or value <= 0 for value in component_counts):
        raise ValueError("component_counts must contain positive integers")
    if len(set(component_counts)) != len(component_counts):
        raise ValueError("component_counts contains a duplicate")
    modes_by_dimension = data["modes_by_dimension"]
    if not isinstance(modes_by_dimension, dict) or set(modes_by_dimension) != {"2", "3"}:
        raise ValueError("modes_by_dimension must define dimensions 2 and 3")
    for dimension, modes in modes_by_dimension.items():
        if not isinstance(modes, list) or not modes:
            raise ValueError("dimension {} must have a nonempty mode list".format(dimension))
        if any(type(value) is not int or value < 0 for value in modes):
            raise ValueError("mode counts must be nonnegative integers")
        if len(set(modes)) != len(modes) or 0 not in modes:
            raise ValueError("each dimension must have unique modes including non-VR mode 0")
    return [
        (components, modes, dimension)
        for components in sorted(component_counts)
        for dimension in sorted(int(value) for value in modes_by_dimension)
        for modes in sorted(modes_by_dimension[str(dimension)])
    ]


def write_if_changed(path, content):
    """Publish a complete UTF-8 file atomically without changing equal files."""
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=path.parent, prefix=path.name + ".", delete=False) as stream:
            temporary_path = Path(stream.name)
            stream.write(content)
        os.replace(temporary_path, path)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()


def launch_name(components, modes, dimension, mapping=None):
    shape = f"_C{components}_M{modes}_D{dimension}"
    return f"LaunchACMRHS{shape}_{mapping}" if mapping else f"LaunchRHS{shape}"


def source_name(components, modes, dimension, mapping=None):
    shape = f"_C{components}_M{modes}_D{dimension}"
    return f"FiniteVolumeACMFluxKernels{shape}_{mapping}.cu" if mapping else f"FiniteVolumeRHSKernels{shape}.cu"


def cuda_source(shape, mapping=None):
    components, modes, dimension = shape
    mechanical = mapping is not None
    return """// Generated by scripts/generate_cauchy_rhs.py; do not edit.
#include "Cauchy/Discretization/CUDA/{implementation}.cu.inc"

namespace DNDS::Cauchy::CUDA::Detail
{{
    void {name}(const RHSFaceLaunch &a{arguments})
    {{
        {launcher}<{components}, {modes}, {dimension}{mapping}>(a{forward});
    }}
}}
""".format(name=launch_name(*shape, mapping), components=components, modes=modes, dimension=dimension,
           implementation="FiniteVolumeACMFluxKernels_Impl" if mechanical else "FiniteVolumeRHSKernels_Polynomial_Impl",
           launcher="LaunchACMRHSShape" if mechanical else "LaunchRHSShape",
           mapping=f", RHSFaceMapping::{mapping}" if mechanical else "",
           arguments="", forward="")


def mappings(shape, mechanical):
    return (ACM_MAPPINGS if shape[1] else ("Thread",)) if mechanical else (None,)


def declarations(shapes, mechanical=False):
    arguments = ""
    entry = "bool TryLaunchFP64ACMRHS" if mechanical else "void LaunchFP64RHS"
    lines = [
        "// Generated by scripts/generate_cauchy_rhs.py; do not edit.",
        "#pragma once", "",
    ]
    if mechanical:
        lines.extend(['#include "Cauchy/Discretization/CUDA/FiniteVolumeRHSKernels.hpp"', ""])
    lines.extend([
        "namespace DNDS::Cauchy::CUDA::Detail", "{",
        "    struct RHSFaceLaunch;", "",
        "    /// Dispatch only the manifest's valid C/M/D polynomial RHS shapes.",
        f"    {entry}(const RHSFaceLaunch &a{arguments});", "",
    ])
    for shape in shapes:
        for mapping in mappings(shape, mechanical):
            lines.append(f"    void {launch_name(*shape, mapping)}(const RHSFaceLaunch &a{arguments});")
    lines.extend(["}", ""])
    return "\n".join(lines)


def dispatcher(shapes, mechanical=False):
    entry = "bool TryLaunchFP64ACMRHS(const RHSFaceLaunch &a)" if mechanical else "void LaunchFP64RHS(const RHSFaceLaunch &a)"
    header = "FiniteVolumeACMFluxKernels_Instantiations" if mechanical else "FiniteVolumeRHSKernels_Instantiations"
    lines = [
        "// Generated by scripts/generate_cauchy_rhs.py; do not edit.",
        '#include "Cauchy/Discretization/CUDA/FiniteVolumeRHSKernels_Shapes.hpp"',
        f'#include "{header}.hpp"', "",
        "namespace DNDS::Cauchy::CUDA::Detail", "{",
        f"    {entry}", "    {",
        "        const bool nonVR = a.controls.direct || a.controls.firstOrder;",
        "        const int modes = nonVR ? 0 : a.controls.modes;",
        "        DNDS_check_throw_info(nonVR || modes != 0,",
        '                              "CUDA polynomial RHS requires a nonzero VR modal count");',
        "        switch (a.controls.components)", "        {",
    ]
    for components in sorted({shape[0] for shape in shapes}):
        lines.extend(["        case {}:".format(components),
                      "            switch (a.controls.dimension)", "            {"])
        for dimension in sorted({shape[2] for shape in shapes if shape[0] == components}):
            lines.extend(["            case {}:".format(dimension),
                          "                switch (modes)", "                {"])
            for shape in shapes:
                if shape[0] == components and shape[2] == dimension:
                    lines.append(f"                case {shape[1]}:")
                    if mechanical and shape[1] == 0:
                        lines.extend(["                    if (a.controls.mapping != RHSFaceMapping::Thread) return false;",
                                      f"                    {launch_name(*shape, 'Thread')}(a);", "                    return true;"])
                    elif mechanical:
                        thread, cta = (launch_name(*shape, mapping) for mapping in ACM_MAPPINGS)
                        lines.extend(["                    if (a.controls.mapping == RHSFaceMapping::CTASegments)",
                                      f"                        {cta}(a);", "                    else",
                                      f"                        {thread}(a);", "                    return true;"])
                    else:
                        lines.append(f"                    return {launch_name(*shape)}(a);")
            lines.extend(["                }", "                break;"])
        lines.extend(["            }", "            break;"])
    lines.append("        }")
    lines.extend(["        return false;"] if mechanical else [
        "        DNDS_check_throw_info(false,", '                              "CUDA polynomial RHS: unsupported component/dimension/modal shape");'])
    lines.extend(["    }", "}", ""])
    return "\n".join(lines)


def cmake_path(path):
    """Use bracket arguments so absolute paths are not interpreted by CMake."""
    value = path.as_posix()
    if "]==]" in value or ";" in value or "\n" in value or "\r" in value:
        raise ValueError("generated output path contains an unsupported CMake list character")
    return "[==[{}]==]".format(value)


def publish_index(index, sources, outputs, declarations_path):
    """Prune retired, unmodified TUs recorded by the previous build-local index."""
    output_directory = index.parent
    current = {p.name for p in sources}
    marker = re.compile(r"# owned-tu ([A-Za-z0-9_]+\.(?:cu|cpp)) ([0-9a-f]{64})")
    if index.is_file() and not index.is_symlink():
        for name, digest in marker.findall(index.read_text(encoding="utf-8")):
            path = output_directory / name
            if name not in current and not path.is_symlink() and path.is_file():
                if hashlib.sha256(path.read_bytes()).hexdigest() == digest:
                    path.unlink()
                else:
                    print(f"Preserved edited former generated source {path}", file=sys.stderr)
    lines = ["# Generated by scripts/generate_cauchy_rhs.py; do not edit."]
    for variable, values in [
        ("DNDS_CAUCHY_RHS_GENERATED_SOURCES", sources),
        ("DNDS_CAUCHY_RHS_GENERATED_OUTPUTS", outputs),
    ]:
        lines.append("set({}".format(variable))
        lines.extend("    {}".format(cmake_path(path)) for path in values)
        lines.append(")")
    lines.append("set(DNDS_CAUCHY_RHS_GENERATED_INCLUDE_DIR {})".format(cmake_path(output_directory)))
    lines.append("set(DNDS_CAUCHY_RHS_GENERATED_DECLARATIONS {})".format(cmake_path(declarations_path)))
    lines.append("")
    lines.extend(f"# owned-tu {path.name} {hashlib.sha256(path.read_bytes()).hexdigest()}" for path in sources)
    write_if_changed(index, "\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    try:
        output_directory = args.output_dir.resolve()
        output_directory.mkdir(parents=True, exist_ok=True)
        index = output_directory / "FiniteVolumeRHSKernels_Sources.cmake"
        sources, headers, contents = [], [], []
        for mechanical, stem in ((False, "FiniteVolumeRHSKernels"), (True, "FiniteVolumeACMFluxKernels")):
            shapes = read_shapes(args.manifest, mechanical)
            header = output_directory / (stem + "_Instantiations.hpp")
            dispatch = output_directory / (stem + "_Instantiations.cpp")
            kernels = [(shape, mapping) for shape in shapes for mapping in mappings(shape, mechanical)]
            cuda_sources = [output_directory / source_name(*shape, mapping) for shape, mapping in kernels]
            sources.extend([dispatch, *cuda_sources])
            headers.append(header)
            contents.extend((path, cuda_source(shape, mapping)) for path, (shape, mapping) in zip(cuda_sources, kernels))
            contents.extend([(header, declarations(shapes, mechanical)), (dispatch, dispatcher(shapes, mechanical))])
        outputs = sources + headers + [index]
        # Render everything before publishing any output. The index is published
        # last so configuration cannot accept an incomplete generated source list.
        for path, content in contents:
            write_if_changed(path, content)
        publish_index(index, sources, outputs, headers[0])
    except (OSError, ValueError, TypeError) as error:
        print("generate_cauchy_rhs: {}".format(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
